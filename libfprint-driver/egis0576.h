/* Bulk endpoints (the 0576 uses 0x01 out / 0x82 in, unlike the 0570). */
#define EGIS0576_EPOUT 0x01
#define EGIS0576_EPIN  0x82

#define EGIS0576_TIMEOUT 10000

/* One 70x57 frame per capture. */
#define EGIS0576_IMGWIDTH  70
#define EGIS0576_IMGHEIGHT 57
#define EGIS0576_IMGSIZE   (EGIS0576_IMGWIDTH * EGIS0576_IMGHEIGHT)  /* 3990 */

/* Command responses are short (7-9 bytes); a 64-byte buffer covers them. */
#define EGIS0576_CMDRESP 64

/* Variable-length EGIS packets (7..18 bytes). */
#define EGIS0576_PKTMAX 18
struct egis_pkt
{
  gsize   len;
  guint8  data[EGIS0576_PKTMAX];
};

/* A packet is an image request when its opcode byte is 0x64. */
#define EGIS0576_IS_IMG_REQ(p) ((p)->data[4] == 0x64)

